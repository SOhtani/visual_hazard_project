def summarize_validity_flags(df: pd.DataFrame, phase_levels: Sequence[str]) -> pd.DataFrame:
    cols = [c for c in VALIDITY_FLAG_COLUMNS if c in df.columns]
    if not cols:
        return pd.DataFrame()
    rows = []
    groupings: List[Tuple[str, List[str]]] = [("case", ["case_id"])]
    for phase_level in phase_levels:
        label_col = f"workflow_{phase_level.lower().replace('-', '')}_label"
        if label_col in df.columns:
            groupings.append((f"case_{phase_level}", ["case_id", label_col]))
    for scope, keys in groupings:
        tmp = df.copy()
        for k in keys:
            tmp[k] = tmp[k].replace("", "NoLabel").fillna("NoLabel")
        for values, g in tmp.groupby(keys, dropna=False):
            if not isinstance(values, tuple):
                values = (values,)
            base = {"scope": scope, "n_frames": int(len(g))}
            for k, v in zip(keys, values):
                base[k] = v
            for col in cols:
                s = pd.to_numeric(g[col], errors="coerce").fillna(0.0) >= 0.5
                base[f"{col}_count"] = int(s.sum())
                base[f"{col}_fraction"] = float(s.mean()) if len(s) else np.nan
            rows.append(base)
    return pd.DataFrame(rows)


def write_csv(df: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)
    print(f"[OK] wrote {path} rows={len(df)}")


def main() -> None:
    args = parse_args()
    case_filter = set(args.case) if args.case else None
    specs = component_specs_from_args(args.component_col, args.include_legacy_badness)

    df = load_metric_frames(args.metrics_dir, case_filter)
    missing = [s.score_col for s in specs if s.score_col not in df.columns]
    if missing:
        print("[WARN] missing score columns skipped:", ", ".join(missing))
        specs = [s for s in specs if s.score_col in df.columns]
    if not specs:
        raise ValueError("No requested component score columns are present in metric CSVs.")

    df = assign_workflow_labels(df, args.annotation_root, args.time_col)
    interval_map = sample_interval_by_case(df, args.time_col)

    global_cutoffs = build_global_cutoffs(df, specs, args.threshold_quantiles)
    phase_cutoffs = build_phase_cutoffs(df, specs, args.threshold_quantiles, args.phase_level)
    case_summary = summarize_case_component(df, specs, args.threshold_quantiles, global_cutoffs, args.time_col, interval_map)
    case_phase_summary = summarize_case_phase_component(
        df, specs, args.threshold_quantiles, global_cutoffs, args.phase_level, args.time_col, interval_map
    )
    validity_summary = summarize_validity_flags(df, args.phase_level)

    score_cols = [s.score_col for s in specs if s.score_col in df.columns]
    corr = df[score_cols].apply(pd.to_numeric, errors="coerce").corr(method="spearman")
    corr.index.name = "score_col"

    component_metadata = pd.DataFrame([s.__dict__ for s in specs])

    print(f"Loaded frames: {len(df)}")
    print(f"Cases: {df['case_id'].nunique()}")
    print("Components:", ", ".join(s.component for s in specs))
    print("Threshold quantiles:", ", ".join(q_name(q) for q in args.threshold_quantiles))
    if args.include_legacy_badness:
        print("[NOTE] legacy badness is summarized as a screening alias, not as a validated composite.")

    if args.dry_run:
        print(case_summary.head(20).to_string(index=False))
        return

    out = args.output_dir
    write_csv(component_metadata, out / "component_metric_metadata.csv")
    write_csv(global_cutoffs, out / "global_component_candidate_cutoffs.csv")
    write_csv(phase_cutoffs, out / "phase_component_candidate_cutoffs.csv")
    write_csv(case_summary, out / "case_component_distribution_summary.csv")
    write_csv(case_phase_summary, out / "case_phase_component_distribution_summary.csv")
    if not validity_summary.empty:
        write_csv(validity_summary, out / "image_validity_flag_summary.csv")
    corr.to_csv(out / "component_spearman_correlation.csv")
    print(f"[OK] wrote {out / 'component_spearman_correlation.csv'} rows={len(corr)}")


if __name__ == "__main__":
    main()
