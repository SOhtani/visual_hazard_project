"""
Summarize per-frame visual-hazard component distributions by case and workflow phase.

This script is exploratory. It does not define final clinical cutoffs. It creates
candidate distribution summaries and distribution-based candidate thresholds for
later visual, surgeon-rating, and clinical-outcome validation.

Inputs should generally be local per-frame metric CSVs generated by
05_compute_frame_visual_hazard_components.py. Outputs may contain case IDs and
local paths, so write them under reports/ and do not commit them to GitHub.
"""

