def infer_case_id_from_path(path: Path) -> str:
    stem = path.stem
    for suffix in ["_frame_scores", "_metrics", "_visual_hazard_components"]:
        if stem.endswith(suffix):
            stem = stem[: -len(suffix)]
    return stem


def list_metric_csvs(metrics_dir: Path, case_filter: Optional[set[str]]) -> List[Path]:
    paths = sorted(p for p in metrics_dir.glob("*.csv") if p.name != SUMMARY_CSV_NAME)
    if case_filter:
        return [p for p in paths if infer_case_id_from_path(p) in case_filter]
    return paths


def load_metric_frames(metrics_dir: Path, case_filter: Optional[set[str]]) -> pd.DataFrame:
    paths = list_metric_csvs(metrics_dir, case_filter)
    if not paths:
        raise FileNotFoundError(f"No metric CSVs found in {metrics_dir}")
    dfs = []
    for path in paths:
        df = pd.read_csv(path)
        if "case_id" not in df.columns:
            df["case_id"] = infer_case_id_from_path(path)
        else:
            df["case_id"] = df["case_id"].fillna(infer_case_id_from_path(path)).astype(str)
        df["source_metric_csv"] = str(path)
        dfs.append(df)
    out = pd.concat(dfs, ignore_index=True, sort=False)
    if "metric_status" in out.columns:
        out = out[(out["metric_status"].isna()) | (out["metric_status"].astype(str) == "ok")].copy()
    return out


def version_key(path: Path) -> Tuple[int, str]:
    name = path.name
    m = re.search(r"_v(\d+)\.json$", name)
    if m:
        return (int(m.group(1)), name)
    return (1, name)


def find_annotation_json(annotation_root: Path, case_id: str) -> Optional[Path]:
    candidates = sorted(annotation_root.glob(f"{case_id}_annotation*.json"), key=version_key)
    candidates = [p for p in candidates if "backup" not in p.name.lower()]
    if not candidates:
        # Some cases may be under nested folders, e.g. residual/excluded folders.
        candidates = sorted(annotation_root.rglob(f"{case_id}_annotation*.json"), key=version_key)
        candidates = [p for p in candidates if "backup" not in p.name.lower()]
    return candidates[-1] if candidates else None


def load_surgcap_segments(annotation_path: Path) -> List[dict]:
    obj = json.loads(annotation_path.read_text(encoding="utf-8"))
    segments = obj.get("active_annotation", {}).get("segments", [])
    cleaned = []
    for s in segments:
        try:
            start = float(s.get("start_sec"))
            end = float(s.get("end_sec"))
        except Exception:
            continue
        if not math.isfinite(start) or not math.isfinite(end) or end < start:
            continue
        cleaned.append(
            {
                "level": str(s.get("level", "")),
                "label": str(s.get("label", "")),
                "start_sec": start,
                "end_sec": end,
            }
        )
    return cleaned


def assign_workflow_labels(df: pd.DataFrame, annotation_root: Optional[Path], time_col: str) -> pd.DataFrame:
    df = df.copy()
    for level in ["Level-0", "Level-1", "Level-2"]:
        df[f"workflow_{level.lower().replace('-', '')}_label"] = ""

    if annotation_root is None:
        return df
    if time_col not in df.columns:
        print(f"[WARN] time column '{time_col}' not found; workflow labels will be blank.")
        return df

    for case_id, idx in df.groupby("case_id").groups.items():
        ann = find_annotation_json(annotation_root, str(case_id))
        if ann is None:
            print(f"[WARN] no annotation JSON found for {case_id}")
            continue
        try:
            segments = load_surgcap_segments(ann)
        except Exception as exc:
            print(f"[WARN] failed to read annotation for {case_id}: {ann} ({exc})")
            continue
        t = pd.to_numeric(df.loc[idx, time_col], errors="coerce")
        for s in segments:
            col = f"workflow_{s['level'].lower().replace('-', '')}_label"
            if col not in df.columns:
                continue
            mask = (t >= s["start_sec"]) & (t <= s["end_sec"])
            if mask.any():
                df.loc[t.index[mask], col] = s["label"]
        print(f"[INFO] assigned workflow labels for {case_id}: {ann.name}")
    return df


def component_specs_from_args(component_cols: Optional[Sequence[str]], include_legacy: bool) -> List[ComponentSpec]:
    if component_cols:
        builtins = {s.score_col: s for s in DEFAULT_COMPONENT_SPECS}
        specs = [builtins.get(c, ComponentSpec(c.replace("_v1", ""), c, "custom", "Custom score column.")) for c in component_cols]
    else:
        specs = list(DEFAULT_COMPONENT_SPECS)
    if include_legacy:
        specs.append(LEGACY_BADNESS_SPEC)
    return specs


def sample_interval_by_case(df: pd.DataFrame, time_col: str) -> Dict[str, float]:
    out: Dict[str, float] = {}
    if time_col not in df.columns:
        return {str(c): 1.0 for c in df["case_id"].unique()}
    for case_id, g in df.groupby("case_id"):
        t = pd.to_numeric(g[time_col], errors="coerce").dropna().sort_values().to_numpy()
        if len(t) >= 2:
            diffs = np.diff(t)
            diffs = diffs[np.isfinite(diffs) & (diffs > 0)]
            out[str(case_id)] = float(np.median(diffs)) if len(diffs) else 1.0
        else:
            out[str(case_id)] = 1.0
    return out


def q_name(q: float) -> str:
    pct = int(round(q * 1000))
    if pct % 10 == 0:
        return f"p{pct // 10}"
    return f"p{pct / 10:g}".replace(".", "p")


def numeric_series(df: pd.DataFrame, col: str) -> pd.Series:
    return pd.to_numeric(df[col], errors="coerce")


def describe_scores(values: pd.Series, quantiles: Sequence[float]) -> Dict[str, float]:
    x = pd.to_numeric(values, errors="coerce").dropna()
    out: Dict[str, float] = {
        "n_nonmissing": int(len(x)),
        "mean": float(x.mean()) if len(x) else np.nan,
        "sd": float(x.std(ddof=1)) if len(x) > 1 else np.nan,
        "min": float(x.min()) if len(x) else np.nan,
        "max": float(x.max()) if len(x) else np.nan,
        "zero_fraction": float((x <= 0).mean()) if len(x) else np.nan,
        "nonzero_fraction": float((x > 0).mean()) if len(x) else np.nan,
    }
    for q in quantiles:
        out[q_name(q)] = float(x.quantile(q)) if len(x) else np.nan
    return out


def max_consecutive_seconds(t: pd.Series, above: pd.Series, sample_interval: float) -> float:
    # Use count-based duration. This is robust to 1 fps sparse review-derived data.
    flags = above.fillna(False).astype(bool).to_numpy()
    best = 0
    current = 0
    for flag in flags:
        if flag:
            current += 1
            best = max(best, current)
        else:
            current = 0
    return float(best * sample_interval)


def build_global_cutoffs(df: pd.DataFrame, specs: Sequence[ComponentSpec], quantiles: Sequence[float]) -> pd.DataFrame:
    rows = []
    for spec in specs:
        if spec.score_col not in df.columns:
            continue
        x = numeric_series(df, spec.score_col).dropna()
        for q in quantiles:
            rows.append(
                {
                    "component": spec.component,
                    "score_col": spec.score_col,
                    "tier": spec.tier,
                    "threshold_scope": "global",
                    "phase_level": "",
                    "phase_label": "",
                    "quantile": q,
                    "quantile_name": q_name(q),
                    "threshold_value": float(x.quantile(q)) if len(x) else np.nan,
                    "n_frames": int(len(x)),
                    "interpretation": spec.interpretation,
                }
            )
    return pd.DataFrame(rows)


def build_phase_cutoffs(df: pd.DataFrame, specs: Sequence[ComponentSpec], quantiles: Sequence[float], phase_levels: Sequence[str]) -> pd.DataFrame:
    rows = []
    for phase_level in phase_levels:
        label_col = f"workflow_{phase_level.lower().replace('-', '')}_label"
        if label_col not in df.columns:
            continue
        phase_labels = df[label_col].replace("", "NoLabel").fillna("NoLabel")
        tmp = df.copy()
        tmp["_phase_label"] = phase_labels
        for phase_label, g in tmp.groupby("_phase_label", dropna=False):
            for spec in specs:
                if spec.score_col not in g.columns:
                    continue
                x = numeric_series(g, spec.score_col).dropna()
                for q in quantiles:
                    rows.append(
                        {
                            "component": spec.component,
                            "score_col": spec.score_col,
                            "tier": spec.tier,
                            "threshold_scope": "phase_specific",
                            "phase_level": phase_level,
                            "phase_label": phase_label,
                            "quantile": q,
                            "quantile_name": q_name(q),
                            "threshold_value": float(x.quantile(q)) if len(x) else np.nan,
                            "n_frames": int(len(x)),
                            "interpretation": spec.interpretation,
                        }
                    )
    return pd.DataFrame(rows)


def summarize_case_component(
    df: pd.DataFrame,
    specs: Sequence[ComponentSpec],
    quantiles: Sequence[float],
    global_thresholds: pd.DataFrame,
    time_col: str,
    interval_map: Dict[str, float],
) -> pd.DataFrame:
    threshold_lookup = {
        (r["score_col"], r["quantile_name"]): r["threshold_value"]
        for _, r in global_thresholds.iterrows()
        if r["threshold_scope"] == "global"
    }
    rows = []
    for case_id, g in df.groupby("case_id"):
        dt = interval_map.get(str(case_id), 1.0)
        for spec in specs:
            if spec.score_col not in g.columns:
                continue
            x = numeric_series(g, spec.score_col)
            row = {
                "case_id": case_id,
                "component": spec.component,
                "score_col": spec.score_col,
                "tier": spec.tier,
                "n_frames": int(len(g)),
                "estimated_duration_sec": float(len(g) * dt),
                "score_time_integral": float(np.nansum(x.to_numpy(dtype=float)) * dt),
                "sample_interval_sec": dt,
                "interpretation": spec.interpretation,
            }
            row.update(describe_scores(x, quantiles))
            for q in quantiles:
                name = q_name(q)
                thr = threshold_lookup.get((spec.score_col, name), np.nan)
                above = x >= thr if np.isfinite(thr) else pd.Series(False, index=g.index)
                row[f"global_{name}_threshold"] = float(thr) if np.isfinite(thr) else np.nan
                row[f"frac_ge_global_{name}"] = float(above.mean()) if len(above) else np.nan
                row[f"seconds_ge_global_{name}"] = float(above.sum() * dt)
                row[f"max_consecutive_seconds_ge_global_{name}"] = max_consecutive_seconds(g.get(time_col, pd.Series(index=g.index)), above, dt)
            rows.append(row)
    return pd.DataFrame(rows)


